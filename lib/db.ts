function sslConfig(connectionString: string): boolean | { rejectUnauthorized: boolean } | undefined {
  let url: URL;
  try {
    url = new URL(connectionString);
  } catch {
    return { rejectUnauthorized: false };
  }

  const sslmode = url.searchParams.get("sslmode");
  if (sslmode === "disable") return false;
  if (sslmode === "verify-ca" || sslmode === "verify-full") return undefined;

  const host = url.hostname.replace(/^\[|\]$/g, "");
  if (host === "localhost" || host === "127.0.0.1" || host === "::1") return false;

  return { rejectUnauthorized: true };
}

export function getPool(): Pool {
  if (!globalForDb.__demonmcPool) {
    const connectionString = process.env.DATABASE_URL;
    if (!connectionString) {
      throw new Error(
        "DATABASE_URL is not set. Add your PostgreSQL connection string to the environment.",
      );
    }

    const ssl = sslConfig(connectionString);
    const pool = new Pool({
      connectionString,
      ...(ssl === undefined ? {} : { ssl }),
      max: 5,
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 10_000,
    });
    pool.on("error", (error) => {
      console.error("PostgreSQL pool error:", error.message);
    });

    globalForDb.__demonmcPool = pool;
  }
  return globalForDb.__demonmcPool;
}

async function createSchema(): Promise<void> {
  const client = await getPool().connect();
  try {
    await client.query("BEGIN");
    // Serialize schema creation across serverless instances.
    await client.query("SELECT pg_advisory_xact_lock($1)", [726202611160001]);
    await client.query(SCHEMA_SQL);
    for (const [key, value] of Object.entries(DEFAULT_SETTINGS)) {
      await client.query(
        "INSERT INTO settings (key, value) VALUES ($1, $2) ON CONFLICT (key) DO NOTHING",
        [key, value],
      );
    }
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK").catch(() => undefined);
    throw error;
  } finally {
    client.release();
  }
}

export function ensureSchema(): Promise<void> {
  globalForDb.__demonmcSchemaPromise ??= createSchema().catch((error) => {
    globalForDb.__demonmcSchemaPromise = undefined;
    throw error;
  });
  return globalForDb.__demonmcSchemaPromise;
}

export async function query<T extends QueryResultRow = QueryResultRow>(
  text: string,
  params: unknown[] = [],
): Promise<QueryResult<T>> {
  await ensureSchema();
  return getPool().query<T>(text, params);
}

export async function withTransaction<T>(
  fn: (client: PoolClient) => Promise<T>,
): Promise<T> {
  await ensureSchema();
  const client = await getPool().connect();
  try {
    await client.query("BEGIN");
    const result = await fn(client);
    await client.query("COMMIT");
    return result;
  } catch (error) {
    await client.query("ROLLBACK").catch(() => undefined);
    throw error;
  } finally {
    client.release();
  }
}

export function isUniqueViolation(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    "code" in error &&
    (error as { code?: unknown }).code === "23505"
  );
}

export async function closePool(): Promise<void> {
  const pool = globalForDb.__demonmcPool;
  globalForDb.__demonmcPool = undefined;
  globalForDb.__demonmcSchemaPromise = undefined;
  if (pool) await pool.end();
}
